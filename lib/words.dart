// ==========================================
// MODELO DE DATOS (CATEGORÍA)
// ==========================================

class Category {
  final String id;
  final String name;
  final String icon;
  final List<String> words;
  final Color color;
  // Optional hint shown to the impostor (empty = use the theme name)
  final String hint;

  const Category({
    required this.id,
    required this.name,
    required this.icon,
    required this.words,
    required this.color,
    this.hint = '',
  });

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'name': name,
      'icon': icon,
      'words': words,
      'colorValue': color.value,
      'hint': hint,
    };
  }

  factory Category.fromMap(Map<String, dynamic> map) {
    return Category(
      id: map['id'],
      name: map['name'],
      icon: map['icon'],
      words: List<String>.from(map['words']),
      color: Color(map['colorValue']),
      hint: map['hint'] ?? '',
    );
  }
}

// Merges the built-in English words with the extra words (lib/extra_words.dart)
// and removes duplicates.
List<Category>? _cachedCategories;

List<Category> getGameCategories([String langCode = 'en']) {
  return _cachedCategories ??= _categoriesEn.map((c) {
    final seen = <String>{};
    final merged = <String>[];
    for (final w in [...c.words, ...(extraWords[c.id] ?? const <String>[])]) {
      if (seen.add(w.trim().toLowerCase())) merged.add(w.trim());
    }
    return Category(
      id: c.id,
      name: c.name,
      icon: c.icon,
      words: merged,
      color: c.color,
    );
  }).toList();
}

